dev = writer.begin_page(A4); y = T; pages = 1
for part in parts:
    if y > T and y + height_of(part) > B:
        writer.end_page(); dev = writer.begin_page(A4); y = T; pages += 1
    st = fitz.Story(html=part, user_css=css, archive=archive)
    while True:
        more, filled = st.place(fitz.Rect(L, y, R, B)); st.draw(dev)
        if not more:
            y = bottom(filled) + 4; break
        writer.end_page(); dev = writer.begin_page(A4); y = T; pages += 1
        if pages > 15:
            raise SystemExit("too many pages")
writer.end_page(); writer.close()

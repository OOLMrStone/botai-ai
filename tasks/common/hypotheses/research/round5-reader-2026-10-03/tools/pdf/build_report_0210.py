A4 = fitz.paper_rect("a4"); L, T, R, B = 45, 40, A4.width - 45, A4.height - 40
archive = fitz.Archive(str(HERE))


def bottom(filled):
    return filled[3] if isinstance(filled, tuple) else filled.y1


def height_of(part):
    st = fitz.Story(html=part, user_css=css, archive=archive)
    _, filled = st.place(fitz.Rect(L, 0, R, 5000))
    return bottom(filled)


out = HERE / "Отчёт руководителю 02.10.pdf"
